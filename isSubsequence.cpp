bool IsSubsequence(const char* a, const char* b, size_t lenA, size_t lenB)
{
    int i = 0;
    int j = 0;
    while (i < lenA && j < lenB)
    {
        if (a[i] == b[j])
            i++;
        j++;
    }
    return i == lenA;
}
/* мы ищем символы строки а в б по порядку, i двигаем только при совпадении, порядок сохраняется, тк не возвращаемся наза по а;
таким образом, если все элементы из а были найдены последовательно в б, то индекс равен длине а, что и проверяется*/
